class RunDigestResponse(BaseModel):
    """
    Compact summary of a run: what a reader needs to judge the outcome, without the
    plot data and the agent's activity log.
    """

    run_id: str = Field(..., description="Unique identifier for the run")
    status: str = Field(..., description="Current run status")
    progress: int = Field(ge=0, le=100, description="Completion percentage (0-100)")
    phase: PhaseInfo | None = Field(default=None, description="Phase of an unfinished run")
    target_variable: str | None = Field(default=None, description="Name of the target column")
    error: str | None = Field(default=None, description="Error message if the run failed")
    summary: dict[str, Any] | None = Field(
        default=None,
        description=(
            "`headline` (the selected equation with its holdout and cross-validation scores), "
            "`equations` (the shortlist), `data` (rows, train/holdout split, what the scores "
            "are measured on), `series` (time structure and derived features, time series "
            "only), `agent`, `literature`, `known_laws`, `explanation`, `warnings`, "
            "`llm_cost_usd`. Null until results exist."
        ),
    )


