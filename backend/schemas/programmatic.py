"""
Pydantic schemas for the Syxplain API.

These schemas are designed for script/notebook usage with a flat,
minimal structure optimized for programmatic clients.
"""

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field, field_validator

from backend.core.constants import STANDARD_ANALYSIS


class AnalyzeParams(BaseModel):
    """
    Parameters for the combined upload+analyze endpoint.

    Flat structure (no nesting) for simpler script usage.
    """

    project_description: str = Field(
        ...,
        min_length=1,
        description="Description of the project and analysis goals",
        json_schema_extra={
            "examples": ["Predict soil phosphorus availability from chemical properties"]
        },
    )
    target_variable: str = Field(
        ...,
        min_length=1,
        description="Name of the target variable (column) to predict",
        json_schema_extra={"examples": ["P_availability"]},
    )
    features: dict[str, str] = Field(
        ...,
        description="Mapping of feature column names to their descriptions",
        json_schema_extra={
            "examples": [{"pH": "Soil pH (H2O)", "organic_C": "Organic carbon (%)"}]
        },
    )
    analysis_type: str = Field(
        default=STANDARD_ANALYSIS,
        description="Deprecated and ignored: every analysis runs the full pipeline, including the literature search",
    )
    gemini_api_key: str | None = Field(
        default=None,
        description="Google Gemini API key (required for users without HUN-REN access)",
    )
    gemini_model: str = Field(
        default="gemini-3.1-pro-preview",
        description="Gemini model to use for LLM operations",
    )
    openai_api_key: str | None = Field(
        default=None,
        description="OpenAI API key for the literature search (without one, users on their own keys get no literature step)",
    )
    deep_research_model: str | None = Field(
        default=None,
        description="Deprecated and ignored",
    )

    @field_validator("features")
    @classmethod
    def features_not_empty(cls, v: dict[str, str]) -> dict[str, str]:
        if not v:
            raise ValueError("At least one feature must be specified")
        return v

    @field_validator("analysis_type")
    @classmethod
    def validate_analysis_type(cls, v: str) -> str:
        # Legacy 'quick'/'deep' are accepted so existing clients keep working
        return STANDARD_ANALYSIS

    class Config:
        json_schema_extra = {
            "example": {
                "project_description": "Predict soil phosphorus availability from chemical properties",
                "target_variable": "P_availability",
                "features": {
                    "pH": "Soil pH measured in H2O",
                    "organic_C": "Organic carbon content (%)",
                    "clay": "Clay fraction (%)",
                },
                "gemini_api_key": "AIza...",
                "gemini_model": "gemini-3.1-pro-preview",
            }
        }


class AnalyzeResponse(BaseModel):
    """Response from the analyze endpoint (202 Accepted)."""

    run_id: str = Field(..., description="Unique identifier for the analysis run")
    status: str = Field(
        default="pending",
        description="Initial run status (always 'pending' on creation)",
    )
    status_url: str = Field(..., description="Relative URL to poll for run status and results")
    cancel_url: str = Field(..., description="Relative URL to cancel the run")

    class Config:
        json_schema_extra = {
            "example": {
                "run_id": "a1b2c3d4-e5f6-7890-abcd-ef1234567890",
                "status": "pending",
                "status_url": "/api/v1/runs/a1b2c3d4-e5f6-7890-abcd-ef1234567890",
                "cancel_url": "/api/v1/runs/a1b2c3d4-e5f6-7890-abcd-ef1234567890/cancel",
            }
        }


class ArtifactInfo(BaseModel):
    """Metadata for a downloadable artifact generated by an analysis run."""

    filename: str = Field(..., description="Artifact filename (e.g. 'pareto_front.png')")
    media_type: str | None = Field(
        default=None,
        description="MIME type of the artifact (e.g. 'image/png', 'application/json')",
    )
    download_url: str = Field(..., description="Relative URL to download the artifact")

    class Config:
        json_schema_extra = {
            "example": {
                "filename": "pareto_front.png",
                "media_type": "image/png",
                "download_url": "/api/v1/runs/a1b2c3d4-.../artifacts/pareto_front.png",
            }
        }


class RunStatusResponse(BaseModel):
    """
    Run status with inline results when completed.

    Poll this endpoint until status is 'completed' or a terminal state.
    """

    run_id: str = Field(..., description="Unique identifier for the run")
    status: str = Field(
        ...,
        description="Current run status: 'pending', 'running', 'completed', 'failed', 'timeout', or 'cancelled'",
    )
    progress: int = Field(ge=0, le=100, description="Completion percentage (0-100)")
    analysis_type: str = Field(
        default="quick",
        description="Type of analysis: 'quick' or 'deep'",
    )
    created_at: datetime | None = Field(
        default=None, description="Timestamp when the run was created (ISO 8601)"
    )
    start_time: datetime | None = Field(
        default=None,
        description="Timestamp when execution started (ISO 8601), null if still pending",
    )
    finish_time: datetime | None = Field(
        default=None,
        description="Timestamp when execution finished (ISO 8601), null if not yet finished",
    )
    duration_seconds: float | None = Field(
        default=None,
        description="Total execution duration in seconds, set only when the run has finished",
    )
    error: str | None = Field(
        default=None,
        description="Error message if the run failed, null otherwise",
    )
    results: dict[str, Any] | None = Field(
        default=None,
        description="Full analysis results (equations, summary, recommendation), present only when status is 'completed'",
    )
    artifacts: list[ArtifactInfo] = Field(
        default_factory=list,
        description="List of downloadable artifact files (plots, JSON), populated on completion",
    )

    class Config:
        json_schema_extra = {
            "examples": [
                {
                    "run_id": "a1b2c3d4-e5f6-7890-abcd-ef1234567890",
                    "status": "running",
                    "progress": 45,
                    "analysis_type": "standard",
                    "created_at": "2026-02-27T10:00:00",
                    "start_time": "2026-02-27T10:00:05",
                    "finish_time": None,
                    "duration_seconds": None,
                    "error": None,
                    "results": None,
                    "artifacts": [],
                },
                {
                    "run_id": "a1b2c3d4-e5f6-7890-abcd-ef1234567890",
                    "status": "completed",
                    "progress": 100,
                    "analysis_type": "standard",
                    "created_at": "2026-02-27T10:00:00",
                    "start_time": "2026-02-27T10:00:05",
                    "finish_time": "2026-02-27T10:03:42",
                    "duration_seconds": 217.0,
                    "error": None,
                    "results": {
                        "equations": [{"equation": "0.42 * pH + 1.3 * organic_C", "loss": 0.012}],
                        "summary": {"key_drivers": ["pH", "organic_C"]},
                    },
                    "artifacts": [
                        {
                            "filename": "pareto_front.png",
                            "media_type": "image/png",
                            "download_url": "/api/v1/runs/a1b2c3d4-.../artifacts/pareto_front.png",
                        }
                    ],
                },
            ]
        }


class RunSummary(BaseModel):
    """Summary of a single run for list responses."""

    run_id: str = Field(..., description="Unique identifier for the run")
    status: str = Field(
        ...,
        description="Current run status: 'pending', 'running', 'completed', 'failed', 'timeout', or 'cancelled'",
    )
    progress: int = Field(ge=0, le=100, description="Completion percentage (0-100)")
    analysis_type: str = Field(
        default="quick",
        description="Type of analysis: 'quick' or 'deep'",
    )
    csv_filename: str = Field(..., description="Name of the uploaded data file")
    target_variable: str | None = Field(
        default=None, description="Name of the target variable being predicted"
    )
    created_at: datetime | None = Field(
        default=None, description="Timestamp when the run was created (ISO 8601)"
    )
    start_time: datetime | None = Field(
        default=None,
        description="Timestamp when execution started (ISO 8601), null if still pending",
    )
    finish_time: datetime | None = Field(
        default=None,
        description="Timestamp when execution finished (ISO 8601), null if not yet finished",
    )

    class Config:
        json_schema_extra = {
            "example": {
                "run_id": "a1b2c3d4-e5f6-7890-abcd-ef1234567890",
                "status": "completed",
                "progress": 100,
                "analysis_type": "standard",
                "csv_filename": "soil_data.csv",
                "target_variable": "P_availability",
                "created_at": "2026-02-27T10:00:00",
                "start_time": "2026-02-27T10:00:05",
                "finish_time": "2026-02-27T10:03:42",
            }
        }


class RunListResponse(BaseModel):
    """Paginated list of runs."""

    items: list[RunSummary] = Field(..., description="List of run summaries for the current page")
    total: int = Field(ge=0, description="Total number of runs matching the query")
    page: int = Field(ge=1, description="Current page number")
    page_size: int = Field(ge=1, description="Number of items per page")
    total_pages: int = Field(ge=0, description="Total number of pages available")

    class Config:
        json_schema_extra = {
            "example": {
                "items": [
                    {
                        "run_id": "a1b2c3d4-e5f6-7890-abcd-ef1234567890",
                        "status": "completed",
                        "progress": 100,
                        "analysis_type": "standard",
                        "csv_filename": "soil_data.csv",
                        "target_variable": "P_availability",
                        "created_at": "2026-02-27T10:00:00",
                        "start_time": "2026-02-27T10:00:05",
                        "finish_time": "2026-02-27T10:03:42",
                    }
                ],
                "total": 1,
                "page": 1,
                "page_size": 10,
                "total_pages": 1,
            }
        }


class CancelResponse(BaseModel):
    """Response from the cancel endpoint."""

    message: str = Field(..., description="Human-readable confirmation message")
    run_id: str = Field(..., description="Identifier of the cancelled run")

    class Config:
        json_schema_extra = {
            "example": {
                "message": "Run cancelled",
                "run_id": "a1b2c3d4-e5f6-7890-abcd-ef1234567890",
            }
        }


class ErrorResponse(BaseModel):
    """Structured error response for Syxplain API endpoints."""

    error: str = Field(
        ...,
        description="Machine-readable error code (e.g. 'validation_error', 'not_found', 'file_error')",
    )
    message: str = Field(..., description="Human-readable error description")
    details: dict[str, Any] | None = Field(
        default=None,
        description="Additional context such as available columns, invalid field names, or file size limits",
    )

    class Config:
        json_schema_extra = {
            "example": {
                "error": "validation_error",
                "message": "Target variable 'nonexistent' not found in uploaded file",
                "details": {"available_columns": ["pH", "organic_C", "clay", "P_availability"]},
            }
        }


class ModelsResponse(BaseModel):
    """Available models for analysis."""

    gemini_models: list[str] = Field(
        ..., description="Available Gemini model identifiers for LLM operations"
    )

    class Config:
        json_schema_extra = {
            "example": {
                "gemini_models": [
                    "gemini-3.1-pro-preview",
                    "gemini-2.5-flash",
                ],
            }
        }
